<#
.SYNOPSIS
    Generates PlaneClouds.h from slicePlaneName of DICOMstack.m: the clouds of reference orientations
    (elevation, azimuth) of the cardiac views hla, vla, lvot and sa, used by the "DICOM plane
    (experimental)" column of bin\DicomShell.dll. Run it again when the clouds change there, then
    tools\Build.ps1 -Cpp.
#>
param([string]$Source = 'C:\Dropbox\mTools\libraries\scratch\DICOM\DICOMstack.m')
$ErrorActionPreference = 'Stop'
$text = Get-Content -LiteralPath $Source -Raw
$out = New-Object Text.StringBuilder
[void]$out.AppendLine('// Generated by New-PlaneClouds.ps1 from slicePlaneName of DICOMstack.m: do not edit.')
[void]$out.AppendLine('// Reference orientations of the cardiac views, as {elevation, azimuth} of the slice normal.')
[void]$out.AppendLine('#pragma once')
foreach ($name in 'HLA', 'VLA', 'LVOT', 'SA') {
    $m = [regex]::Match($text, "if isempty\(\s*$name\s*\),\s*$name\s*=\s*sph2cart\(\s*\[([^\]]+)\]\s*\)")
    if (-not $m.Success) { throw "Cloud $name not found in $Source" }
    $pairs = $m.Groups[1].Value -split ';' | Where-Object { $_.Trim() }
    [void]$out.AppendLine("static const double Cloud$name[][2] = {")
    foreach ($p in $pairs) {
        $v = $p -split ','
        if ($v.Count -ne 2) { throw "Bad pair in $name : $p" }
        [void]$out.AppendLine("    { $($v[0].Trim()), $($v[1].Trim()) },")
    }
    [void]$out.AppendLine('};')
    Write-Host "$name : $($pairs.Count) orientations"
}
$target = Join-Path (Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)) 'src\PlaneClouds.h'
[IO.File]::WriteAllText($target, ($out.ToString() -replace "`r?`n", "`r`n"), (New-Object Text.UTF8Encoding($false)))
Write-Host "Written $target"
